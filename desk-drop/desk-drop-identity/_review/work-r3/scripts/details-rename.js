const fs=require('fs'),path=require('path'),{chromium}=require('playwright');
const SB=path.resolve(__dirname,'../sb2/desk-drop-identity');
(async()=>{const b=await chromium.launch(); const ctx=await b.newContext({acceptDownloads:true}); const p=await ctx.newPage();
await p.goto('file://'+SB+'/details.html'); await p.waitForTimeout(800);
const vals={FOUNDER_NAME:'Sam Rivera',PHONE:'(212) 555-0147',EMAIL:'sam@shelfwise.example',POSTAL_ADDRESS:'PO Box 1234, New York, NY 10010'};
for(const [k,v] of Object.entries(vals)) await p.fill(`input[data-k="${k}"]`,v);
await p.check('#no-site');
const [dl]=await Promise.all([p.waitForEvent('download'),p.click('#save')]);
await dl.saveAs(SB+'/system/brand.js');
await p.reload(); await p.waitForTimeout(800);
console.log('status after reload:', await p.$eval('#status',e=>e.innerText));
await p.screenshot({path:path.resolve(__dirname,'../out/details-after-save.png'),fullPage:true});
await b.close();})();
