#!/usr/bin/env python3
"""Regenerate the column tables in handoff/how-to-fill-handoff-files.md from tools/build_tracker.py.

    python3 tools/build_handoff_tables.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import build_tracker as B   # noqa: E402

START, END = "<!-- columns:start (generated by tools/build_handoff_tables.py; do not edit by hand) -->", "<!-- columns:end -->"


def table(title, specs, intake=None):
    t = f"\n### {title}\n\n| # | Column | Meaning | Source |\n| --- | --- | --- | --- |\n"
    i = 1
    for k in (intake or []):
        t += f"| {i} | `{k}` | Copied from the intake row | CONTRACTS 6.3 |\n"
        i += 1
    for k, kind, w, h, m in specs:
        t += f"| {i} | `{k}` | {h.replace('|', '/')} | {m} |\n"
        i += 1
    return t


def main():
    p = os.path.join(ROOT, "handoff", "how-to-fill-handoff-files.md")
    s = open(p, encoding="utf-8").read()
    a, b = s.index(START) + len(START), s.index(END)
    body = table("signed_offices.csv", B.SIGNED_EXTRA, B.OFFICE_INTAKE) + table("paid_brands.csv", B.PAID_EXTRA, B.BRAND_INTAKE)
    body += "\n### pipeline_log.csv\n\n`" + ", ".join(B.PIPELINE_COLS) + "` (exactly these nine, in this order).\n"
    open(p, "w", encoding="utf-8").write(s[:a] + "\n" + body + s[b:])
    print("updated", p)


if __name__ == "__main__":
    main()
