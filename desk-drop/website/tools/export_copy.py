#!/usr/bin/env python3
"""Regenerate the copy deck section of COPY.md from the live pages, so the deck never drifts
from the site. The pages are the one place copy is edited; this script only reads them.
Run from website/:  python3 tools/export_copy.py
Values from site.config.js (name, tagline, status line, contact placeholders) are shown in {braces}.
"""
import os, re
from html.parser import HTMLParser

WEB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(WEB, "site")
PAGES = [("index", "Home"), ("brands", "For brands"), ("offices", "For offices"), ("privacy", "Privacy notice"),
         ("survey-privacy", "Survey privacy notice"), ("404", "Page not found")]
BLOCK = {"h1": "# ", "h2": "## ", "h3": "### ", "p": "", "li": "- ", "dt": "**Q:** ", "dd": "A: ", "legend": "Field group / question: ",
         "label": "Label: ", "button": "Button: ", "figcaption": "Caption: ", "option": "Option: ", "a": None, "title": "Page title: "}


class Deck(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out, self.stack, self.buf, self.skip, self.in_header = [], [], [], 0, False

    def flush(self, tag):
        text = re.sub(r"\s+", " ", "".join(self.buf)).strip()
        self.buf = []
        if text and BLOCK.get(tag) is not None:
            self.out.append(BLOCK[tag] + text)

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ("script", "style", "svg", "noscript"):
            self.skip += 1
        if a.get("aria-hidden") == "true" and tag == "div":
            self.skip += 1
            self.stack.append("skipdiv")
            return
        if tag == "meta" and a.get("name") == "description":
            self.out.append("Meta description: " + a.get("content", ""))
        if "data-config" in a and not self.skip:
            self.buf.append("{" + a["data-config"] + "}")
        if tag in BLOCK and BLOCK[tag] is not None:
            if self.buf and self.stack:
                self.flush(self.stack[-1] if self.stack[-1] in BLOCK else "p")
            self.stack.append(tag)
        else:
            self.stack.append(tag)

    def handle_endtag(self, tag):
        if tag in ("script", "style", "svg", "noscript"):
            self.skip -= 1
        while self.stack:
            t = self.stack.pop()
            if t == "skipdiv":
                self.skip -= 1
                if tag == "div":
                    break
                continue
            if t in BLOCK and BLOCK[t] is not None:
                self.flush(t)
            if t == tag:
                break

    def handle_data(self, d):
        if not self.skip:
            self.buf.append(d)


def deck_for(page):
    src = open(os.path.join(SITE, page + ".html"), encoding="utf-8").read()
    src = re.sub(r"<!-- HEADER:START.*?<!-- HEADER:END -->", "", src, flags=re.S)
    src = re.sub(r"<!-- FOOTER:START.*?<!-- FOOTER:END -->", "", src, flags=re.S)
    src = re.sub(r'<div class="hp".*?</div>', "", src, flags=re.S)
    d = Deck()
    d.feed(src)
    lines, last = [], None
    for l in d.out:
        if l != last:
            lines.append(l)
        last = l
    return "\n".join(lines)


def main():
    cfg = open(os.path.join(SITE, "site.config.js"), encoding="utf-8").read()
    keys = ["BRAND_NAME", "TAGLINE", "ROSTER_STATUS", "CONTACT_EMAIL", "POSTAL_ADDRESS", "FOUNDER_NAME", "COMPANY_LEGAL_NAME", "DOMAIN"]
    rows = ["| Key | Value |", "| --- | --- |"] + ["| `%s` | %s |" % (k, (re.search(k + r':\s*"([^"]*)"', cfg) or [None, ""])[1]) for k in keys]
    parts = ["Generated by `tools/export_copy.py` from `site/*.html` and `site/site.config.js`. Do not edit here; edit the page, then re-run the script.",
             "", "### Values from site.config.js", ""] + rows
    hdr = open(os.path.join(SITE, "index.html"), encoding="utf-8").read()
    parts += ["", "### On every page", "", "- Staging bar (only while STAGING is true): " + re.sub(r"<[^>]+>", "", re.search(r'<p class="staging-bar">(.*?)</p>', hdr).group(1)),
              "- Header: {BRAND_NAME}, links For brands, For offices", "- Footer: {BRAND_NAME}, {TAGLINE}; For brands, For offices, Privacy, Survey privacy notice; Email: {CONTACT_EMAIL}; Mail: {POSTAL_ADDRESS}"]
    for page, title in PAGES:
        parts += ["", "---", "", "### Page: %s (`site/%s.html`)" % (title, page), "", deck_for(page)]
    body = "\n".join(parts)
    path = os.path.join(WEB, "COPY.md")
    doc = open(path, encoding="utf-8").read()
    new = re.sub(r"<!-- GENERATED:START -->.*?<!-- GENERATED:END -->", lambda m: "<!-- GENERATED:START -->\n" + body + "\n<!-- GENERATED:END -->", doc, flags=re.S)
    open(path, "w", encoding="utf-8").write(new)
    print("COPY.md deck regenerated (%d lines)" % body.count("\n"))


if __name__ == "__main__":
    main()
